const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const { ReleaseStore } = require('../vortex/release-store.cjs')
const root = path.resolve(__dirname, '../.runtime/pack-admin')
const instance = path.join(process.env.USERPROFILE, 'curseforge/minecraft/Instances/Vortex Modded')
const metadata = JSON.parse(fs.readFileSync(path.join(instance, 'minecraftinstance.json')))
const addon = metadata.installedAddons.find(a => a.name === 'Quark')
if(!addon || addon.fileNameOnDisk !== 'Quark-4.1-486.jar') throw Error('Quark esperado no encontrado')
const source = path.join(instance, 'mods', addon.fileNameOnDisk)
const bytes = fs.readFileSync(source), official = addon.installedFile
if(bytes.length !== official.fileLength || !official.hashes.length || !official.hashes.every(h => [1,2].includes(h.type) && crypto.createHash(h.type === 1 ? 'sha1' : 'md5').update(bytes).digest('hex') === h.value.toLowerCase())) throw Error('Quark no coincide con sus hashes oficiales')
const store = new ReleaseStore(root)
const channel = JSON.parse(fs.readFileSync(path.join(root, 'channels/test.json')))
const previous = JSON.parse(JSON.parse(fs.readFileSync(path.join(root, 'releases', channel.version + '.json'))).payload)
const old = previous.files.find(f => f.path.startsWith('mods/') && /^Quark-/i.test(path.basename(f.path)))
if(!old) throw Error('Quark anterior ausente')
const name = 'vortex-1.0.3-quark486', version = '1.0.3-quark486'
store.create(name, version, 'ChatGPT')
let draft = store.edit(name, 0, d => { d.files = previous.files; d.notes = 'Quark 4.1-486 de Vortex Modded, verificado por hashes, para conservar NeoForge 21.1.250.' })
draft = store.add(name, draft.revision, source, 'mods/' + addon.fileNameOnDisk, 'managed', old.path)
draft = store.edit(name, draft.revision, d => { d.files.find(f => f.path === 'mods/' + addon.fileNameOnDisk).source = { provider: 'curseforge', projectId: addon.addonID, fileId: official.id, title: addon.name } })
store.publish(name, draft.revision, 'test')
const prepared = require('../vortex/test-release.cjs').prepareTestRelease(path.resolve(__dirname, '../../.runtime/data/instances'), version)
console.log(JSON.stringify({ version, replaced: old.path, installed: addon.fileNameOnDisk, mods: prepared.mods, published: 'test' }))
