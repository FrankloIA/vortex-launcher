const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const assert = require('node:assert/strict')
const Zip = require('adm-zip')
const { ReleaseStore, applyRelease, verify, hash } = require('../vortex/release-store.cjs')
const live = path.resolve(__dirname, '../.runtime/pack-admin')
const channelBytes = fs.readFileSync(path.join(live, 'channels/test.json'))
const channel = JSON.parse(channelBytes)
const releaseBytes = fs.readFileSync(path.join(live, 'releases', channel.version + '.json'))
assert.equal(hash(releaseBytes), channel.releaseSha256)
const base = verify(JSON.parse(releaseBytes), fs.readFileSync(path.join(live, 'public-signing-key.pem')))
const work = fs.mkdtempSync(path.resolve(__dirname, '../.runtime/upgrade-check-'))
const store = new ReleaseStore(path.join(work, 'admin'))
const instance = path.join(work, 'instance')
const keys = crypto.generateKeyPairSync('ed25519')
fs.writeFileSync(path.join(store.root, 'private-signing-key.pem'), keys.privateKey.export({ type: 'pkcs8', format: 'pem' }))
fs.writeFileSync(path.join(store.root, 'public-signing-key.pem'), keys.publicKey.export({ type: 'spki', format: 'pem' }))
const key = keys.publicKey
const reader = sha => fs.readFileSync(path.join(fs.existsSync(path.join(store.root, 'blobs', sha)) ? store.root : live, 'blobs', sha))
function envelope(version, files) {
    const manifest = { ...base, version, files }
    const payload = JSON.stringify(manifest)
    return { payload, signature: crypto.sign(null, Buffer.from(payload), keys.privateKey).toString('base64') }
}
function fixture(version) {
    const zip = new Zip()
    zip.addFile('pack.mcmeta', Buffer.from(JSON.stringify({ pack: { pack_format: 34, description: 'Prueba aislada de actualización ' + version } })))
    const data = zip.toBuffer(), sha256 = hash(data)
    fs.mkdirSync(path.join(store.root, 'blobs'), { recursive: true })
    fs.writeFileSync(path.join(store.root, 'blobs', sha256), data)
    return { path: 'resourcepacks/vortex-update-check-' + version + '.zip', size: data.length, sha256, policy: 'managed' }
}
const first = fixture('A'), second = fixture('B')
const releaseA = envelope('upgrade-check-A', [...base.files, first])
const releaseB = envelope('upgrade-check-B', [...base.files, second])
const installed = applyRelease(instance, releaseA, key, reader)
const options = path.join(instance, 'options.txt'), world = path.join(instance, 'saves/preservation-check/level.dat')
fs.writeFileSync(options, 'volume:0.37\nuser-preferences-preserved:true\n')
fs.mkdirSync(path.dirname(world), { recursive: true }); fs.writeFileSync(world, 'synthetic-world-preservation-marker')
const preferencesHash = hash(fs.readFileSync(options)), worldHash = hash(fs.readFileSync(world))
const upgraded = applyRelease(instance, releaseB, key, reader)
assert.equal(upgraded.changed, 2)
assert.equal(fs.existsSync(path.join(instance, first.path)), false)
assert.equal(hash(fs.readFileSync(path.join(instance, second.path))), second.sha256)
assert.equal(hash(fs.readFileSync(options)), preferencesHash)
assert.equal(hash(fs.readFileSync(world)), worldHash)
for(const file of base.files.filter(f => f.policy === 'managed')) assert.equal(hash(fs.readFileSync(path.join(instance, file.path))), file.sha256)
const repeated = applyRelease(instance, releaseB, key, reader)
assert.equal(repeated.changed, 0)
assert.throws(() => applyRelease(instance, releaseA, key, reader, { afterChange: () => { throw Error('fallo simulado') } }), /fallo simulado/)
assert.equal(JSON.parse(fs.readFileSync(path.join(instance, '.vortex-owned.json'))).version, 'upgrade-check-B')
assert.equal(hash(fs.readFileSync(path.join(instance, second.path))), second.sha256)
assert.equal(fs.existsSync(path.join(instance, first.path)), false)
assert.equal(hash(fs.readFileSync(path.join(live, 'channels/test.json'))), hash(channelBytes))
const report = { baseVersion: base.version, baseFiles: base.files.length, mods: base.files.filter(f => f.path.startsWith('mods/')).length, initialChanges: installed.changed, upgradeChanges: upgraded.changed, repeatedChanges: repeated.changed, preservedPreferences: true, preservedWorldMarker: true, allManagedHashesVerified: true, rollbackVerified: true, liveChannelUnchanged: true, gameLaunchTested: false }
fs.writeFileSync(path.resolve(__dirname, '../../docs/stage-3/upgrade-check-result.json'), JSON.stringify(report, null, 2) + '\n')
console.log(JSON.stringify(report, null, 2))
